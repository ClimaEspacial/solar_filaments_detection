"""Fit the candidate re-scorer (see rescore.py) on the pipeline's own proposals.

Candidates are generated by running the full pipeline at a deliberately low detector
threshold over the *training* images of a fold, and each candidate is labelled with the
annotator support of the ground-truth cluster it matches (0 if it matches none). The
re-scorer then learns to predict that support from shape, photometric and context
descriptors, and inference keeps candidates whose predicted support clears a threshold.
"""
import argparse
import random

import numpy as np
import torch
from ultralytics import YOLO

from solar_filaments.config import CropConfig, Paths, UNetConfig, YoloConfig
from solar_filaments.data.coco import Dataset, load_image, load_split, merge_annotator_records, polygon_to_mask
from solar_filaments.inference import predict_instances
from solar_filaments.models.refiner import load_refiner
from solar_filaments.rescore import (FEATURES, DiskGeometry, Rescorer, candidate_features,
                                     features_to_array, fit_rescorer)


def add_args(parser: argparse.ArgumentParser) -> None:
    parser.add_argument("--fold", type=int, default=None,
                         help="fit on this fold's TRAINING images; checkpoint rescorer[_fold<N>].pkl")
    parser.add_argument("--conf-thres", type=float, default=0.10,
                         help="detector threshold used to generate candidates - deliberately low, so the "
                              "re-scorer sees the marginal proposals it will have to judge")
    parser.add_argument("--mask-thresh", type=float, default=0.5)
    parser.add_argument("--mask-nms-thresh", type=float, default=0.15)
    parser.add_argument("--threshold", type=float, default=0.32,
                         help="predicted-support cut stored with the model; the marginal analysis gives "
                              "PQ/(2*mean IoU) ~ 0.32 at our operating point. Re-sweep at evaluate time")
    parser.add_argument("--limit", type=int, default=0, help="use only N training images (smoke tests)")
    parser.add_argument("--detector", choices=("yolo", "yolo-seg"), default="yolo",
                         help="candidate source. Must match the detector the re-scorer will be used with: "
                              "a re-scorer fitted on one detector's proposals does not transfer to another")
    parser.add_argument("--imgsz", type=int, default=1024)
    parser.add_argument("--semantic-source", action="store_true",
                         help="also feed the full-disk segmenter's connected components in as candidates, "
                              "the way an ensemble would - measured 2026-09-07: this raises recall a lot "
                              "(GT miss 20.6%%->9.7%%) but collapses PQ (0.44->0.36) through false positives, "
                              "so it is exactly the pool a discriminator has to clean up")
    parser.add_argument("--no-semantic", action="store_true",
                         help="skip the full-disk semantic features (faster; loses the strongest "
                              "detector-independent signal)")
    parser.add_argument("--seed", type=int, default=0)


def run(args: argparse.Namespace) -> None:
    paths = Paths()
    paths.ensure()
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print("device:", device)

    dataset = Dataset(paths.train_ann_path)
    train_ids, _ = load_split(paths.split_path_for(args.fold))
    files = sorted({dataset.images_by_id[i]["file_name"] for i in train_ids if i in dataset.images_by_id})
    if args.limit:
        files = files[:args.limit]

    suffix = f"_fold{args.fold}" if args.fold is not None else ""
    base = f"{YoloConfig().name}_seg" if args.detector == "yolo-seg" else YoloConfig().name
    yolo = YOLO(str(paths.runs_dir / f"{base}{suffix}" / "weights" / "best.pt"))
    unet = load_refiner(paths.ckpt_dir / f"unet{suffix}_best.pt", device,
                        use_edge_attention=UNetConfig().use_edge_attention)

    segmenter = None
    if not args.no_semantic:
        from solar_filaments.detectors.fulldisk import FullDiskSegmenter, load_flat_unet
        weights = paths.ckpt_dir / f"flat_unet{suffix}_best.pt"
        if weights.exists():
            model, imgsz = load_flat_unet(str(weights), device)
            segmenter = FullDiskSegmenter(model, device, imgsz=imgsz)
        else:
            print(f"no full-disk segmenter at {weights} - continuing without semantic features")

    crop_cfg = CropConfig()
    feats, support = [], []
    print(f"generating candidates over {len(files)} training images at conf={args.conf_thres} ...")
    for n, fn in enumerate(files, start=1):
        img = load_image(paths.train_img_dir / fn)
        geom = DiskGeometry.from_image(img)
        prob = segmenter.probability_map(img) if segmenter is not None else None

        clusters = [(polygon_to_mask(c["segmentation"], img.shape[0], img.shape[1]).astype(bool), c["support"])
                    for c in merge_annotator_records(dataset, fn, "union")]

        rk = dict(crop_size=crop_cfg.crop_size, pad_factor=crop_cfg.pad_factor,
                  min_crop_side=crop_cfg.min_crop_side, mask_thresh=args.mask_thresh,
                  mask_nms_thresh=args.mask_nms_thresh, use_tta=True)
        if args.detector == "yolo-seg":
            from solar_filaments.detectors import YoloSegDetector
            from solar_filaments.inference import refine_candidates
            cands = YoloSegDetector(yolo, conf_thres=args.conf_thres, iou_thres=0.5,
                                    imgsz=args.imgsz).detect(img)
            if args.semantic_source and segmenter is not None:
                cands = cands + segmenter.detect(img)
            label_map, scores = refine_candidates(img, cands, unet, device, **rk)
        else:
            label_map, scores = predict_instances(
                paths.train_img_dir / fn, yolo, unet, device, conf_thres=args.conf_thres, **rk)

        for i, score in enumerate(scores, start=1):
            mask = label_map == i
            if not mask.any():
                continue
            best = 0.0
            for gt_mask, sup in clusters:
                union = (mask | gt_mask).sum()
                if union and (mask & gt_mask).sum() / union > 0.5:
                    best = max(best, sup)
            feats.append(candidate_features(img, mask, score, geom, prob))
            support.append(best)
        if n % 50 == 0:
            print(f"  {n}/{len(files)} images, {len(feats)} candidates")

    support = np.array(support, dtype=np.float32)
    print(f"\n{len(feats)} candidates: {(support > 0).sum()} matched ({(support > 0).mean():.1%}), "
          f"{(support == 0).sum()} spurious")
    print(f"support distribution: " + ", ".join(f"{v:.2f}->{(support == v).sum()}"
                                                 for v in np.unique(support)))

    random.seed(args.seed)
    model = fit_rescorer(feats, support, seed=args.seed)
    rescorer = Rescorer(model, threshold=args.threshold)
    out = paths.ckpt_dir / f"rescorer{suffix}.pkl"
    rescorer.save(out)

    # Honest skill estimate: 5-fold cross-validated AUC. The in-sample number is
    # meaningless here (an unregularized booster reaches 0.998 by memorizing).
    from sklearn.model_selection import KFold
    X = features_to_array(feats)
    y = support > 0
    oof = np.zeros(len(y))
    for tr, te in KFold(n_splits=5, shuffle=True, random_state=args.seed).split(X):
        oof[te] = fit_rescorer([feats[i] for i in tr], support[tr], seed=args.seed).predict(X[te])

    def auc_of(scores):
        order = np.argsort(scores)
        ranks = np.empty(len(scores), dtype=float)
        ranks[order] = np.arange(1, len(scores) + 1)
        n1 = y.sum()
        return (ranks[y].sum() - n1 * (n1 + 1) / 2) / (n1 * (len(y) - n1))

    print(f"\ncross-validated AUC (matched vs spurious): {auc_of(oof):.3f}")
    print(f"  box confidence alone, same candidates : {auc_of(X[:, FEATURES.index('box_conf')]):.3f}")
    print(f"saved to {out}")
